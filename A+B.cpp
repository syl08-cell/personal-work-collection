/*题目描述

给你两个集合A,B，要求A∪B.

输入描述

每组输入数据分为三行,第一行有两个数字n,m(0<n,m≤100),分别表示集合A和集合B的元素个数.后两行分别表示集合A和集合B.每个元素为不超出[0,10000]范围的整数 , 每个元素之间有一个空格隔开.
保证集合A和集合B的数字按照升序给出.
当输入m,n均为0时表示处理结束。

输出描述

针对每组数据输出一行数据,表示合并后的集合,要求从小到大输出,每个元素之间有一个空格隔开.

样例输入 1 

1 2
1
2 3
1 2
1
1 2
0 0
样例输出 1 

1 2 3
1 2
*/

#include <iostream>
using namespace std;

int main(){//想到了插树法
    int n,m;
    do{
        cin >> n >> m;
        int arr[10001]={0};
        int a;
        for(int j=0;j<n+m;++j){
        	cin >> a;
        	arr[a]=1;
        }
        for(int i=0;i<10001;++i){
            if(arr[i]==1){
                cout << i << " ";
            }
        }
        cout << '\n';
        
    }while(n!=0&&m!=0);
        
    return 0;    
}